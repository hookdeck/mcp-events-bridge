/*
 * Generates src/core/sources/source-types.generated.ts from Event Gateway's OpenAPI spec: every source type that
 * receives webhooks from a service, and the credential fields its verification takes, so `source({ type })` is
 * typed per source type. Run it when Event Gateway adds source types:
 *
 *   npx tsx scripts/generate-source-types.ts
 *
 * The spec is public; no API key is needed.
 */
import fs from 'node:fs';

const SPEC_URL = 'https://api.hookdeck.com/2026-09-01/openapi';
const OUT = new URL('../src/core/sources/source-types.generated.ts', import.meta.url);

/**
 * Source types `source()` doesn't offer: Hookdeck's own (publish API, Outpost, managed, MCP Events callbacks), the
 * generic ones the bridge handles itself (`webhook` is `source({ type: 'webhook', verification })`), and pull-based
 * types that don't receive webhooks.
 */
const EXCLUDED = new Set(['PUBLISH_API', 'HOOKDECK_OUTPOST', 'MANAGED', 'MCP_EVENTS', 'WEBHOOK', 'HTTP', 'GOOGLE_PUBSUB']);

type Schema = { $ref?: string; type?: string; properties?: Record<string, Schema>; required?: string[]; oneOf?: Schema[]; anyOf?: Schema[] };

const spec = (await (await fetch(SPEC_URL)).json()) as { components: { schemas: Record<string, Schema> } };
const schemas = spec.components.schemas;
const deref = (s: Schema | undefined): Schema | undefined => (s?.$ref ? schemas[s.$ref.split('/').pop()!] : s);

/** `webhook_secret_key` is `secret`; everything else is camelCase. */
const optionName = (field: string) => (field === 'webhook_secret_key' ? 'secret' : field.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase()));

interface Entry {
  type: string;
  sourceType: string;
  fields: Array<{ option: string; field: string; required: boolean }>;
}

const entries: Entry[] = [];
const skipped: string[] = [];
for (const name of Object.keys(schemas).sort()) {
  if (!name.startsWith('SourceTypeConfig') || name === 'SourceTypeConfig') continue;
  const sourceType = name.slice('SourceTypeConfig'.length);
  if (EXCLUDED.has(sourceType)) continue;
  const auth = deref(schemas[name]!.properties?.auth);
  // Types with a choice of verification methods (GitLab, Grafana, Azure Event Grid, ...) aren't offered yet.
  if (auth?.oneOf || auth?.anyOf) {
    skipped.push(sourceType);
    continue;
  }
  const props = auth?.properties ?? {};
  const fields = Object.keys(props).map((field) => ({ option: optionName(field), field, required: (auth?.required ?? []).includes(field) }));
  // The bridge relays only requests Event Gateway verified; a type with no credentials to configure isn't offered
  // until that's checked for it.
  if (!fields.some((f) => f.required)) {
    skipped.push(sourceType);
    continue;
  }
  entries.push({ type: sourceType.toLowerCase(), sourceType, fields });
}

const key = (name: string) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : `'${name}'`);
const str = (value: string) => `'${value}'`;

const credentialType = (e: Entry) =>
  e.fields.length ? `{ ${e.fields.map((f) => `${f.option}${f.required ? '' : '?'}: Credential`).join('; ')} }` : 'Record<never, never>';

const out = `// Generated by scripts/generate-source-types.ts from ${SPEC_URL}. Do not edit.
// ${entries.length} source types. Not offered yet (several verification methods, or no credentials): ${skipped.join(', ') || 'none'}.
import type { EnvRef } from '../config.js';

type Credential = string | EnvRef;

/** Each source type's credential options, as \`source({ type, ...credentials })\` takes them. */
export interface SourceTypeCredentials {
${entries.map((e) => `  ${key(e.type)}: ${credentialType(e)};`).join('\n')}
}

export type SourceTypeName = keyof SourceTypeCredentials;

/** Event Gateway's name for each source type, and how each credential option maps to its source \`auth\` config. */
export const SOURCE_TYPES: Record<SourceTypeName, { sourceType: string; auth: Record<string, { field: string; required: boolean }> }> = {
${entries
  .map((e) => `  ${key(e.type)}: { sourceType: ${str(e.sourceType)}, auth: {${e.fields.length ? ` ${e.fields.map((f) => `${f.option}: { field: ${str(f.field)}, required: ${f.required} }`).join(', ')} ` : ''}} },`)
  .join('\n')}
};
`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${OUT.pathname}: ${entries.length} source types (${skipped.length} skipped: ${skipped.join(', ')})`);
